_current = os.getenv("LAB_LANGUAGE", "en").lower()
if _current not in LANGUAGES:
    _current = "en"


def get_language() -> str:
    return _current


def set_language(language: str) -> str:
    global _current
    _current = language if language in LANGUAGES else "en"
    return _current


def label(language: str = None) -> str:
    return LANGUAGES[language or _current]["label"]


def direction(language: str = None) -> str:
    return LANGUAGES[language or _current]["dir"]


def tr(key: str, language: str = None, **kwargs) -> str:
    language = language or _current
    text = MESSAGES.get(language, {}).get(key, MESSAGES["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text
